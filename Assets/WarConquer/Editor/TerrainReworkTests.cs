        static void Capture(string name)
        {
            camera.Render();var previous=RenderTexture.active;RenderTexture.active=render;var image=new Texture2D(1600,1000,TextureFormat.RGB24,false);image.ReadPixels(new Rect(0,0,1600,1000),0,0);image.Apply();RenderTexture.active=previous;
