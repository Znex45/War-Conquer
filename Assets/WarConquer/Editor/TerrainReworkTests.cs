        const string Pending="TerrainRework.Pending";
        public static void BeginBatch(){SessionState.SetBool(Pending,true);EditorSceneManager.OpenScene("Assets/WarConquer/Scenes/WarConquer_Graybox.unity");EditorApplication.isPlaying=true;}
        [InitializeOnLoadMethod]static void Register(){EditorApplication.update+=Tick;}
        static void Tick()
        {
            if(!EditorApplication.isPlaying||EditorApplication.isCompiling)return;
            if(SessionState.GetBool(Pending,false)){SessionState.SetBool(Pending,false);running=true;step=0;due=EditorApplication.timeSinceStartup+3;}
            if(!running||EditorApplication.timeSinceStartup<due)return;
            try
            {
                if(step==0)
                {
                    Rules();visual=New();foreach(var tile in visual.State.tiles.Where(t=>t.baseOwner<0).Take(16))visual.Place("qa-terrain-unit",tile.id%4,tile.id);fixture=new GameObject("Terrain stress QA");world=fixture.AddComponent<Board3DScene>();world.Initialize();world.ResizeTexture(1280,800);
                    step++;due=EditorApplication.timeSinceStartup+.1;return;
                }
                if(step<=3)
                {
                    int count=step==1?10:step==2?25:64;
                    var watch=Stopwatch.StartNew();foreach(var t in visual.State.tiles.Take(count))t.biome=biomes[t.id%biomes.Length];
                    visual.Notify("stress");world.Sync(visual,new HashSet<int>(),new HashSet<int>(),-1);watch.Stop();
                    int before=fixture.GetComponentsInChildren<Transform>().Length;for(int i=0;i<10;i++)world.Sync(visual,new HashSet<int>(),new HashSet<int>(),-1);
                    Check(before==fixture.GetComponentsInChildren<Transform>().Length,"Unchanged refresh accumulates VFX");
                    Debug.Log("TERRAIN_STRESS: "+count+" slabs, "+watch.ElapsedMilliseconds+" ms rebuild, "+fixture.GetComponentsInChildren<ParticleSystem>().Length+" particle systems; 10 refreshes stable.");
                    if(step==3)DetailChecks();
                    step++;due=EditorApplication.timeSinceStartup+.2;return;
                }
                if(step==4)
                {
                    for(int cycle=1;cycle<8;cycle++){foreach(var t in visual.State.tiles.Take(64))t.biome=biomes[(t.id+cycle)%biomes.Length];world.Sync(visual,new HashSet<int>(),new HashSet<int>(),-1);}
                    foreach(var t in visual.State.tiles)t.biome=Biome.Neutral;world.Sync(visual,new HashSet<int>(),new HashSet<int>(),-1);
                    step++;due=EditorApplication.timeSinceStartup+1.4;return;
                }
                if(step==5)
                {
                    Check(fixture.GetComponentsInChildren<ParticleSystem>().Length==0,"Old biome/dust particles leaked after neutral reset");
                    UnityEngine.Object.Destroy(fixture);
                    Gallery();step++;due=EditorApplication.timeSinceStartup+.12;return;
                }
                if(step==6){Capture("terraform-start");step++;due=EditorApplication.timeSinceStartup+.4;return;}
                if(step==7){Capture("terraform-emerge");step++;due=EditorApplication.timeSinceStartup+1.2;return;}
                Capture("biomes-final");Check(gallery.GetComponentsInChildren<ParticleSystem>().All(p=>p.name!="TerraformDustVFX"),"Dust remains after transition");
                Debug.Log("TERRAIN_VISUAL_PASSED: seven persistent biomes, dust/emergence, cleanup, stable refreshes, transparent water and environmental fauna. Screenshots: Library/TerrainQA.");
                running=false;EditorApplication.Exit(0);
            }
            catch(Exception ex){Debug.LogException(ex);running=false;EditorApplication.Exit(1);}
        }
        static void DetailChecks()
        {
            using(var factory=new BoardMeshFactory())Check(factory.Vortex.normals.All(n=>n.y>.9f),"Vortex faces point below slab");
            var center=Tile(visual);center.biome=Biome.Void;var p=visual.Place("qa-terrain-unit",0,center.id);visual.Notify("detail QA");world.Sync(visual,new HashSet<int>(),new HashSet<int>(),center.id);
            Check(world.UnitVisual(p.id).localScale.x==1.25f,"Unit scale missing");
            Check(world.LeaderVisual(0).Find("Observador").localScale.x==2.6f,"Leader scale missing");
            Check(world.Pick(world.ViewportOf(center.id,.9f))==center.id,"Enlarged unit cannot be picked");
            Check(world.Zoom==Board3DScene.DefaultZoom,"Default closer framing missing");
            world.BoardCamera.Render();var prev=RenderTexture.active;RenderTexture.active=world.Texture;
            var img=new Texture2D(world.Texture.width,world.Texture.height,TextureFormat.RGB24,false);img.ReadPixels(new Rect(0,0,img.width,img.height),0,0);img.Apply();RenderTexture.active=prev;
            Directory.CreateDirectory("Library/TerrainQA");File.WriteAllBytes("Library/TerrainQA/board-detail.png",img.EncodeToPNG());UnityEngine.Object.Destroy(img);
            // Camera regression: old zoom, pitch and pan limits must not return.
            foreach(float pitch in new[]{0f,90f,180f,270f,413f})
            {
                world.Pitch=pitch;world.Zoom=.02f;world.Pan=new Vector2(2500,-2500);world.UpdateCamera();
                Check(world.Zoom==.02f&&world.Pan.x==2500,"Camera still constrained");
                float size=world.BoardCamera.orthographicSize;world.ZoomAt(2,Vector2.one*.5f);
                Check(world.BoardCamera.orthographicSize<size,"Zoom fails at free orbit angle");
                world.Zoom=50;world.UpdateCamera();Check(world.Zoom==50,"Close zoom still constrained");
                Check(Mathf.Abs(Mathf.DeltaAngle(world.Pitch,pitch))<.01f,"Orbit pitch still constrained");
                world.DragCamera(Vector2.one*.5f,new Vector2(.6f,.6f));
                Check(!float.IsNaN(world.Pan.x)&&!float.IsNaN(world.PanHeight),"Invalid camera pan");
            }
            world.Zoom=Board3DScene.DefaultZoom;world.Pan=Vector2.zero;world.PanHeight=0;world.Pitch=53;world.Yaw=0;world.UpdateCamera();
            Check(world.Pick(world.ViewportOf(center.id,.9f))==center.id,"Pick failed after camera reset");
            Debug.Log("CAMERA_FREE_PASSED: near/far zoom, full orbit, unbounded pan, horizon controls and reset picking.");
            Debug.Log("TERRAIN_DETAIL_PASSED: upward vortex, larger units/leaders, real pick and closer board framing.");
        }
